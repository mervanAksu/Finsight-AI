const DICTS: Record<Lang, Record<MsgKey, string>> = { tr, en };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MsgKey, vars?: Vars): string {
  const template = DICTS[lang][key] ?? tr[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_m: string, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}

export type TFunc = (key: MsgKey, vars?: Vars) => string;

export interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: TFunc;
}

export const I18nContext = createContext<I18nValue>({
  lang: "tr",
  setLang: () => undefined,
  t: (key, vars) => translate("tr", key, vars),
});

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

